// التحقق من سلامة البيانات الأولية عند تحميلها
export function validateSeedData(): { ok: boolean; errors: string[] } {
  const errors: string[] = [];
  let totalWeight = 0;
  let totalIndicators = 0;

  for (const c of SEED_CRITERIA) {
    totalWeight += c.weight;
    let subWeight = 0;
    let critIndicators = 0;

    if (c.subCriteria) {
      for (const s of c.subCriteria) {
        subWeight += s.weight;
        critIndicators += s.indicators.length;
        for (const ind of s.indicators) {
          if (!/^\d+-\d+(-\d+)?$/.test(ind.code)) {
            errors.push(`رمز مؤشر غير صالح: ${ind.code}`);
          }
          if (ind.evidence.length === 0) {
            errors.push(`المؤشر ${ind.code} بدون أدلة`);
          }
        }
      }
      if (subWeight !== c.weight) {
        errors.push(
          `مجموع أوزان المعايير الفرعية للمعيار ${c.code} (${subWeight}) لا يساوي وزن المعيار (${c.weight})`
        );
      }
    } else if (c.flatIndicators) {
      critIndicators += c.flatIndicators.length;
      for (const ind of c.flatIndicators) {
        if (!/^\d+-\d+$/.test(ind.code)) {
          errors.push(`رمز مؤشر غير صالح: ${ind.code}`);
        }
        if (ind.evidence.length === 0) {
          errors.push(`المؤشر ${ind.code} بدون أدلة`);
        }
      }
    }
    totalIndicators += critIndicators;
  }

  if (totalWeight !== 100) {
    errors.push(`مجموع أوزان المعايير الرئيسية = ${totalWeight}، يجب أن يكون 100`);
  }

  return { ok: errors.length === 0, errors };
}


