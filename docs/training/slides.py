def content(title, unit, bullets, img=None, img2=None, notes="", size=19):
    s = base(title, unit, notes)
    top, hgt = Inches(1.6), Inches(5.3)
    if img:
        textbox(s, Inches(6.9), top, Inches(5.9), hgt, bullets, size=size)
        if img2:
            picture(s, img, Inches(0.5), top, Inches(3.1), hgt)
            picture(s, img2, Inches(3.65), top, Inches(3.1), hgt)
        else:
            picture(s, img, Inches(0.5), top, Inches(6.2), hgt)
    else:
        textbox(s, Inches(0.8), top, Inches(12.0), hgt, bullets, size=size + 1)
    return s


