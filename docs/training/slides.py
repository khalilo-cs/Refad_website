def style_run(run, size, color, bold=False):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color
    run.font.name = FONT
    rpr = run._r.get_or_add_rPr()
    rpr.set("lang", "ar-YE")
    for tag in ("a:cs",):
        el = rpr.find(qn(tag))
        if el is None:
            el = rpr.makeelement(qn(tag), {})
            rpr.append(el)
        el.set("typeface", FONT)


def rtl(p, align=PP_ALIGN.RIGHT):
    p.alignment = align
    p._p.get_or_add_pPr().set("rtl", "1")


def add_rich(p, text, size, color, bold=False):
    """يدعم **نص عريض** داخل السطر."""
    parts = re.split(r"(\*\*[^*]+\*\*)", text)
    for part in parts:
        if not part:
            continue
        b = bold or (part.startswith("**") and part.endswith("**"))
        run = p.add_run()
        run.text = part.strip("*") if b and part.startswith("**") else part
        style_run(run, size, color, b)


def textbox(slide, x, y, w, h, lines, size=18, color=INK, bold=False, align=PP_ALIGN.RIGHT, anchor=MSO_ANCHOR.TOP, space=6):
    box = slide.shapes.add_textbox(x, y, w, h)
    tf = box.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = anchor
    tf.margin_left = tf.margin_right = Inches(0.08)
    for i, line in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        rtl(p, align)
        p.space_after = Pt(space)
        sz = size
        if isinstance(line, tuple):
            line, sz = line
        add_rich(p, line, sz, color, bold)
    return box


def rect(slide, x, y, w, h, fill, shape=MSO_SHAPE.RECTANGLE):
    s = slide.shapes.add_shape(shape, x, y, w, h)
    s.fill.solid()
    s.fill.fore_color.rgb = fill
    s.line.fill.background()
    s.shadow.inherit = False
    return s


CROP_DIR = tempfile.mkdtemp(prefix="rifad-slides-")


def focus(path):
    """صورة نافذة منبثقة فوق خلفية معتمة: تُقصّ إلى النافذة نفسها لتظهر مقروءة على الشريحة."""
    with Image.open(path) as im:
        g = im.convert("L")
        box = g.point(lambda v: 255 if v >= 246 else 0).getbbox()
        if not box:
            return path
        bw, bh = box[2] - box[0], box[3] - box[1]
        if bw * bh > 0.55 * im.width * im.height or bw < 200 or bh < 150:
            return path
        pad = 14
        box = (max(0, box[0] - pad), max(0, box[1] - pad), min(im.width, box[2] + pad), min(im.height, box[3] + pad))
        out = os.path.join(CROP_DIR, os.path.basename(path))
        im.crop(box).save(out, quality=90)
        return out


def picture(slide, path, x, y, w, h):
    path = focus(path)
    with Image.open(path) as im:
        iw, ih = im.size
    scale = min(w / iw, h / ih)
    pw, ph = int(iw * scale), int(ih * scale)
    px, py = x + (w - pw) // 2, y + (h - ph) // 2
    pic = slide.shapes.add_picture(path, px, py, pw, ph)
    pic.line.color.rgb = RGBColor(0xCB, 0xD5, 0xE1)
    pic.line.width = Pt(1)
    return pic


def table(slide, x, y, w, rows, widths, size=14, row_h=0.42):
    # الأعمدة تُعكس يدوياً بدل خاصية rtl للجدول، لأن بعض البرامج (LibreOffice وGoogle Slides) تتجاهلها
    rows = [list(reversed(r)) for r in rows]
    widths = list(reversed(widths))
    nrows, ncols = len(rows), len(rows[0])
    shape = slide.shapes.add_table(nrows, ncols, x, y, w, Inches(row_h * nrows))
    tbl = shape.table
    total = sum(widths)
    for i, wd in enumerate(widths):
        tbl.columns[i].width = int(w * wd / total)
    for r, row in enumerate(rows):
        for c, val in enumerate(row):
            cell = tbl.cell(r, c)
            cell.margin_left = cell.margin_right = Inches(0.08)
            cell.margin_top = cell.margin_bottom = Inches(0.04)
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            cell.fill.solid()
            cell.fill.fore_color.rgb = NAVY if r == 0 else (SOFT if r % 2 == 0 else WHITE)
            tf = cell.text_frame
            tf.word_wrap = True
            p = tf.paragraphs[0]
            rtl(p)
            add_rich(p, str(val), size, WHITE if r == 0 else INK, r == 0)
    return shape


